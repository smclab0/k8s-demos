#!/usr/bin/env python3
"""Generates DMOSHP's overlays and fleet.yaml's target list from the cluster
labels, like ../../dmobnk/targets/generate.py:

  shop=true   the online shop      (shop.<address>.sslip.io)
  sok=true    the self-checkout    (sok.<address>.sslip.io)
  admin=true  adds Kube Power, at /admin on the first app's host

They combine freely. Without shop or sok a cluster gets the shop (the root
kustomization). Writes targets/<combo>/kustomization.yaml, admin/<combo>/
and the block in ../fleet.yaml between the BEGIN/END markers.

Where Kube Power runs, Fleet doesn't own the apps' replica counts (Kube
Power scales them; Fleet's server-side apply would refuse to upgrade over
that): each Deployment's count moves to the dmobnk.smclab.net/replicas
annotation, which Kube Power applies."""
import itertools
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "# Generated by targets/generate.py. Edit that, not this.\n"
APPS = {
    "shop": {"res": "shop", "deploy": "shop-web", "prefix": "shop", "name": "the shop", "site": "dmoshp-shop"},
    "sok": {"res": "sok", "deploy": "sok-web", "prefix": "sok", "name": "the self-checkout", "site": "dmoshp-sok"},
}
ORDER = ["shop", "sok"]
REPLICAS = 2   # shop.yaml and sok.yaml


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def admin_component(apps):
    combo = "-".join(apps)
    lead = APPS[apps[0]]
    deploys = [APPS[a]["deploy"] for a in apps]
    role = f"""{HEADER}# What DMOSHP's Kube Power may do, all within the dmoshp namespace.
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: kube-power
  namespace: dmoshp
rules:
  # Read: the cluster map, deployments table and events.
  - apiGroups: [""]
    resources: ["pods", "events"]
    verbs: ["list"]
  - apiGroups: ["apps"]
    resources: ["deployments"]
    verbs: ["list"]
  # Kill a pod.
  - apiGroups: [""]
    resources: ["pods"]
    verbs: ["delete"]
  # Scale out and rolling restart, on these deployments only.
  - apiGroups: ["apps"]
    resources: ["deployments", "deployments/scale"]
    resourceNames: [{", ".join(deploys)}]
    verbs: ["patch"]
  # Its sign-in password: read it, or create it on first start.
  - apiGroups: [""]
    resources: ["secrets"]
    resourceNames: ["dmoshp-admin"]
    verbs: ["get"]
  - apiGroups: [""]
    resources: ["secrets"]
    verbs: ["create"]
  # Its own Ingress, which it creates (owned by its Deployment) and keeps on
  # its app's host.
  - apiGroups: ["networking.k8s.io"]
    resources: ["ingresses"]
    resourceNames: ["kube-power"]
    verbs: ["get", "patch"]
  - apiGroups: ["networking.k8s.io"]
    resources: ["ingresses"]
    resourceNames: ["{lead["deploy"]}"]
    verbs: ["get"]
  - apiGroups: ["networking.k8s.io"]
    resources: ["ingresses"]
    verbs: ["create"]
  - apiGroups: ["apps"]
    resources: ["deployments"]
    resourceNames: ["kube-power"]
    verbs: ["get"]
"""
    env = [("ORG_NAME", "DMOSHP"), ("ADMIN_SECRET", "dmoshp-admin"), ("ADMIN_BASE", "/admin"), ("APP_URL", "/"),
           ("APP_NAME", lead["name"]), ("HOST_PREFIX", lead["prefix"]), ("ADMIN_APPS", ",".join(deploys)),
           ("ADMIN_HPA", ""), ("ADMIN_SURGE", ""), ("ADMIN_CRON", ""), ("FOLLOW_INGRESS", lead["deploy"])]
    env_yaml = "\n".join(f'                  - {{name: {k}, value: "{v}"}}' for k, v in env)
    reps = "".join(f"""  - target: {{kind: Deployment, name: {d}}}
    patch: |-
      - op: remove
        path: /spec/replicas
      - op: add
        path: /metadata/annotations
        value: {{dmobnk.smclab.net/replicas: "{REPLICAS}"}}
""" for d in deploys)
    kust = f"""{HEADER}# Kube Power for {", ".join(APPS[a]["name"] for a in apps)}, at /admin on {lead["name"]}'s host.
apiVersion: kustomize.config.k8s.io/v1alpha1
kind: Component
components:
  - ../base
resources:
  - role.yaml
patches:
  - target: {{kind: Deployment, name: kube-power}}
    patch: |-
      apiVersion: apps/v1
      kind: Deployment
      metadata: {{name: kube-power}}
      spec:
        template:
          spec:
            containers:
              - name: kube-power
                env:
{env_yaml}
                  - name: SITE_HOST
                    valueFrom: {{configMapKeyRef: {{name: {lead["site"]}, key: host, optional: true}}}}
                  - name: INGRESS_CLASS
                    valueFrom: {{configMapKeyRef: {{name: {lead["site"]}, key: ingressClass, optional: true}}}}
{reps}"""
    write(f"admin/{combo}/role.yaml", role)
    write(f"admin/{combo}/kustomization.yaml", kust)


def target(apps, admin):
    combo = "-".join(apps) + ("-admin" if admin else "")
    res = "\n".join(f"  - ../../{APPS[a]['res']}" for a in apps)
    comp = f"components:\n  - ../../admin/{'-'.join(apps)}\n" if admin else ""
    write(f"targets/{combo}/kustomization.yaml", f"""{HEADER}# DMOSHP: {", ".join(APPS[a]["name"] for a in apps)}{" with Kube Power" if admin else ""}.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../base
{res}
{comp}""")
    return combo


def main():
    for d in os.listdir(os.path.join(ROOT, "admin")):
        if d != "base":
            shutil.rmtree(os.path.join(ROOT, "admin", d))
    for d in os.listdir(os.path.join(ROOT, "targets")):
        if os.path.isdir(os.path.join(ROOT, "targets", d)):
            shutil.rmtree(os.path.join(ROOT, "targets", d))
    sets = [list(c) for n in range(len(ORDER), 0, -1) for c in itertools.combinations(ORDER, n)]
    combos = []   # (name, labels, dir)
    for apps in sets:
        admin_component(apps)
        for admin in (True, False):
            combos.append((target(apps, admin), apps + (["admin"] if admin else [])))
    # admin=true alone: the shop with Kube Power.
    combos.append(("shop-admin-nolabel", ["admin"], "shop-admin"))
    combos = [(c[0], c[1], c[2] if len(c) > 2 else c[0]) for c in combos]
    combos.sort(key=lambda c: -len(c[1]))
    block = ""
    for name, labels, d in combos:
        sel = "\n".join(f'        {l}: "true"' for l in labels)
        block += f"""  - name: {name}
    clusterSelector:
      matchLabels:
{sel}
    kustomize:
      dir: targets/{d}
"""
    p = os.path.join(ROOT, "fleet.yaml")
    s = open(p).read()
    a, b = s.index("  # BEGIN generated by targets/generate.py\n"), s.index("  # END generated\n")
    s = s[:a] + "  # BEGIN generated by targets/generate.py\n" + block + s[b:]
    open(p, "w").write(s)
    print(f"wrote {len(sets) * 2} overlays and {len(combos)} Fleet targets")


if __name__ == "__main__":
    main()
